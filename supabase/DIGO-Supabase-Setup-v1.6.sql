-- Message and emote server-side throttles, regardless of frontend.
create or replace function public.limit_chat() returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if (select count(*) from public.messages m where m.user_id=new.user_id and m.created_at>now()-interval '10 seconds')>=4 then
    raise exception 'Slow down: four messages per ten seconds.';
  end if;
  return new;
end; $$;
create trigger messages_throttle before insert on public.messages for each row execute function public.limit_chat();
create or replace function public.limit_emotes() returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if exists(select 1 from public.emotes e where e.user_id=new.user_id and e.created_at>now()-interval '1.2 seconds') then
    raise exception 'Emotes are on cooldown';
  end if;
  return new;
end; $$;
create trigger emotes_throttle before insert on public.emotes for each row execute function public.limit_emotes();

-- Limit private-room creation to reduce spam and database growth.
create or replace function public.limit_private_rooms() returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if new.is_private and (select count(*) from public.rooms r where r.owner_id=new.owner_id and r.created_at>now()-interval '1 hour')>=5 then
    raise exception 'Maximum five private rooms per hour';
  end if;
  return new;
end; $$;
create trigger private_room_throttle before insert on public.rooms for each row execute function public.limit_private_rooms();

-- Private invite validation: no private room discovery without the code.
create or replace function public.join_private_room(p_invite_code text)
returns uuid language plpgsql security definer set search_path=public,pg_temp as $$
declare v_room uuid; v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception 'Sign in first'; end if;
  select id into v_room from public.rooms where is_private=true and invite_code=p_invite_code;
  if v_room is null then raise exception 'Invite not found'; end if;
  insert into public.room_members(room_id,user_id) values(v_room,v_uid) on conflict do nothing;
  return v_room;
end; $$;

-- A game question is chosen by the database. The browser receives only public clues.
create or replace function public.start_room_game(p_room_id uuid,p_kind text)
returns uuid language plpgsql security definer set search_path=public,pg_temp as $$
declare v_uid uuid:=auth.uid(); v_prompt public.game_prompts%rowtype; v_game uuid;
begin
  if v_uid is null or not public.is_room_member(p_room_id) then raise exception 'Join this room first'; end if;
  if p_kind not in ('would_rather','emoji_guess') then raise exception 'Unknown game'; end if;
  update public.game_sessions set status='finished' where room_id=p_room_id and status='active' and ends_at<=now();
  if exists(select 1 from public.game_sessions where room_id=p_room_id and status='active') then raise exception 'A game is already running'; end if;
  select * into v_prompt from public.game_prompts where kind=p_kind order by random() limit 1;
  if v_prompt.id is null then raise exception 'No questions configured'; end if;
  insert into public.game_sessions(room_id,kind,prompt_id,prompt,emoji,option_a,option_b,created_by)
  values(p_room_id,p_kind,v_prompt.id,v_prompt.prompt,v_prompt.emoji,v_prompt.option_a,v_prompt.option_b,v_uid)
  returning id into v_game;
  return v_game;
end; $$;

-- Votes and answers are verified server-side; 5 incorrect guesses max per game.
create or replace function public.submit_game_action(p_game_id uuid,p_answer text)
returns jsonb language plpgsql security definer set search_path=public,pg_temp as $$
declare v_uid uuid:=auth.uid(); v_game public.game_sessions%rowtype; v_correct boolean:=false; v_attempts integer;
begin
  if v_uid is null then raise exception 'Sign in first'; end if;
  select * into v_game from public.game_sessions where id=p_game_id for update;
  if v_game.id is null or v_game.status<>'active' or v_game.ends_at<=now() then raise exception 'This round has ended'; end if;
  if not public.is_room_member(v_game.room_id) then raise exception 'Join this room first'; end if;
  if exists(select 1 from public.game_actions where game_id=p_game_id and user_id=v_uid) then raise exception 'You already completed this round'; end if;
  if v_game.kind='would_rather' then
    if p_answer not in ('a','b') then raise exception 'Choose A or B'; end if;
    insert into public.game_actions(room_id,game_id,user_id,choice,correct) values(v_game.room_id,p_game_id,v_uid,p_answer,false);
    return jsonb_build_object('correct',false,'points',0,'note','Your vote is in!');
  end if;
  insert into public.game_guess_attempts(game_id,user_id,attempts) values(p_game_id,v_uid,0) on conflict do nothing;
  select attempts into v_attempts from public.game_guess_attempts where game_id=p_game_id and user_id=v_uid for update;
  if v_attempts>=5 then raise exception 'Five guesses used for this round'; end if;
  update public.game_guess_attempts set attempts=attempts+1 where game_id=p_game_id and user_id=v_uid;
  select (lower(trim(answer))=lower(trim(p_answer))) into v_correct from public.game_prompts where id=v_game.prompt_id;
  if not v_correct then return jsonb_build_object('correct',false,'points',0,'note','Not quite! Try another guess.'); end if;
  insert into public.game_actions(room_id,game_id,user_id,choice,correct) values(v_game.room_id,p_game_id,v_uid,'',true);
  return jsonb_build_object('correct',true,'points',100,'note','Correct! +100 points 🎉');
end; $$;
revoke all on function public.join_private_room(text),public.start_room_game(uuid,text),public.submit_game_action(uuid,text) from public;
grant execute on function public.join_private_room(text),public.start_room_game(uuid,text),public.submit_game_action(uuid,text) to authenticated;

