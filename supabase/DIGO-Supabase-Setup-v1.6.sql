-- Helpers run as the database owner, avoiding recursive RLS on members.
create or replace function public.can_access_room(p_room_id uuid)
returns boolean language sql stable security definer set search_path=public,pg_temp as $$
  select exists(
    select 1 from public.rooms r
    where r.id=p_room_id and (
      not r.is_private or r.owner_id=(select auth.uid()) or
      exists(select 1 from public.room_members m where m.room_id=r.id and m.user_id=(select auth.uid()))
    )
  );
$$;
create or replace function public.is_room_member(p_room_id uuid)
returns boolean language sql stable security definer set search_path=public,pg_temp as $$
  select exists(select 1 from public.room_members m where m.room_id=p_room_id and m.user_id=(select auth.uid()));
$$;
create or replace function public.can_access_room_topic(p_topic text)
returns boolean language plpgsql stable security definer set search_path=public,pg_temp as $$
begin
  if p_topic !~ '^room:[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$' then return false; end if;
  return public.can_access_room(substring(p_topic from 6)::uuid);
end; $$;
