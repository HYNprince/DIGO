-- Friend requests use RPC only: checks mutual blocks and throttles repeated attempts.
create or replace function public.request_friend(p_target uuid)
returns void language plpgsql security definer set search_path=public,pg_temp as $$
declare v_uid uuid:=auth.uid(); v_existing public.friend_requests%rowtype;
begin
 if v_uid is null or p_target is null or p_target=v_uid then raise exception 'Invalid player'; end if;
 if not exists(select 1 from public.profiles where id=p_target) then raise exception 'Player unavailable'; end if;
 if exists(select 1 from public.blocks where (blocker_id=v_uid and blocked_id=p_target) or (blocker_id=p_target and blocked_id=v_uid)) then raise exception 'Request unavailable'; end if;
 select * into v_existing from public.friend_requests where (from_id=v_uid and to_id=p_target) or (from_id=p_target and to_id=v_uid) for update;
 if v_existing.id is not null then
   if v_existing.status='pending' and v_existing.to_id=v_uid then
     update public.friend_requests set status='accepted' where id=v_existing.id;
     return;
   end if;
   raise exception 'Request already exists';
 end if;
 if (select count(*) from public.friend_requests where from_id=v_uid and created_at>now()-interval '1 hour') >= 10 then
   raise exception 'Friend request limit reached';
 end if;
 insert into public.friend_requests(from_id,to_id) values(v_uid,p_target);
end; $$;
revoke all on function public.request_friend(uuid) from public;
grant execute on function public.request_friend(uuid) to authenticated;

create or replace function public.are_friends(a uuid,b uuid)
returns boolean language sql stable security definer set search_path=public,pg_temp as $$
 select exists(select 1 from public.friend_requests
 where status='accepted' and ((from_id=a and to_id=b) or (from_id=b and to_id=a)))
 and not exists(select 1 from public.blocks
 where (blocker_id=a and blocked_id=b) or (blocker_id=b and blocked_id=a));
$$;
revoke all on function public.are_friends(uuid,uuid) from public;
grant execute on function public.are_friends(uuid,uuid) to authenticated;

create table if not exists public.direct_messages (
 id uuid primary key default gen_random_uuid(),
 from_id uuid not null references public.profiles(id) on delete cascade,
 to_id uuid not null references public.profiles(id) on delete cascade,
 body text not null check (char_length(trim(body)) between 1 and 500),
 created_at timestamptz not null default now(),
 constraint no_self_dm check (from_id<>to_id)
);
create index if not exists direct_messages_sender_time on public.direct_messages(from_id,created_at desc);
create index if not exists direct_messages_recipient_time on public.direct_messages(to_id,created_at desc);
alter table public.direct_messages enable row level security;
drop policy if exists dm_friend_read_v16 on public.direct_messages;
create policy dm_friend_read_v16 on public.direct_messages for select to authenticated
using ((from_id=(select auth.uid()) or to_id=(select auth.uid())) and public.are_friends(from_id,to_id));
drop policy if exists dm_friend_send_v16 on public.direct_messages;
create policy dm_friend_send_v16 on public.direct_messages for insert to authenticated
with check (from_id=(select auth.uid()) and public.are_friends(from_id,to_id));
grant select,insert on public.direct_messages to authenticated;
create or replace function public.limit_direct_messages() returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
begin
 if (select count(*) from public.direct_messages where from_id=new.from_id and created_at>now()-interval '10 seconds')>=4 then
  raise exception 'Slow down: four DMs per ten seconds';
 end if;
 return new;
end; $$;
drop trigger if exists dm_throttle_v16 on public.direct_messages;
create trigger dm_throttle_v16 before insert on public.direct_messages for each row execute function public.limit_direct_messages();

-- Reporting a DM can be reviewed privately by a moderator using admin access.
create table if not exists public.direct_message_reports (
 id uuid primary key default gen_random_uuid(),
 reporter_id uuid not null references public.profiles(id) on delete cascade,
 message_id uuid not null references public.direct_messages(id) on delete cascade,
 reason text not null check(reason in ('Spam or scam','Harassment or hate','Sharing private information','Sexual or unsafe content')),
 created_at timestamptz not null default now()
);
alter table public.direct_message_reports enable row level security;
drop policy if exists dm_report_read_v16 on public.direct_message_reports;
create policy dm_report_read_v16 on public.direct_message_reports for select to authenticated using (reporter_id=(select auth.uid()));
drop policy if exists dm_report_write_v16 on public.direct_message_reports;
create policy dm_report_write_v16 on public.direct_message_reports for insert to authenticated
with check(reporter_id=(select auth.uid()) and exists(
 select 1 from public.direct_messages m where m.id=message_id and (m.from_id=reporter_id or m.to_id=reporter_id)
));
grant select,insert on public.direct_message_reports to authenticated;

